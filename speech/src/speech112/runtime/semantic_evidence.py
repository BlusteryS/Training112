"""Explicit card-field evidence in unpunctuated operator speech."""

import re

from speech112.runtime.context_input import operator_text

_FIELDS = {
    "incident": (r"\b(?:что (?:случилось|произошло)|какая (?:обстановка|ситуация)|"
                 r"(?:опишите|описать) (?:обстановку|ситуацию|происшествие)|причин\w* звонка|"
                 r"что именно произошло|расскажите что случилось|причин\w* обращения|"
                 r"что заставило (?:вас )?набрать)\b",),
    "address": (r"\b(?:адрес\w*|на какой улице|(?:назовите|уточните|скажите|запишите) улиц\w*|"
                r"улиц\w* и (?:дом|номер)|подъезд\w*|номер дома|"
                r"куда (?:\w+ )?(?:ехать|приехать|направить|отправить)|"
                r"где (?:вы (?:находитесь|сейчас)|это|именно|произошло|случилось|находится)|"
                r"место (?:вызова|происшествия)|назовите место|"
                r"где (?:конкретно )?требуется|населенн\w* пункт|местоположени\w*)\b",),
    "name": (r"\b(?:как вас зовут|(?:ваше|свое) имя|имя\b|фамили\w*|представьтесь|"
             r"как (?:к вам|могу к вам) обращаться|как я могу вас называть|"
             r"кто (?:звонит|говорит|сообщает)|с кем (?:я )?имею дело)\b",),
    "phone": (r"\b(?:телефон\w*|мобильн\w*|перезвон\w*|контактн\w* номер|"
              r"номер (?:для связи|для обратного звонка|по которому)|"
              r"(?:ваш|свой|у вас|по какому) номер\w*|номер (?:сотового|телефона))\b",),
    "victim_count": (r"\b(?:сколько (?:всего )?(?:пострадавш\w*|ранен\w*|людей|человек)|"
                     r"сколько их|ранен\w* всего сколько|число людей пострад\w*|"
                     r"количеств\w* (?:пострадавш\w*|ранен\w*|людей)|"
                     r"один (?:пострадавший|человек) или несколько)\b",),
    "age": (r"\b(?:сколько (?:ему|ей|вам|человеку|пострадавшему) (?:примерно )?лет|"
            r"сколько лет (?:ему|ей|человеку|пострадавшему)|возраст\w*|"
            r"пострадавш\w* примерно сколько лет|"
            r"ребенок или взрослый|пожилой человек или молодой)\b",),
    "breathing": (r"\b(?:дыш\w*|дыхани\w*|вдох\w*|грудная клетка поднимается)\b",),
    "consciousness": (r"\b(?:сознани\w*|отвечает (?:вам|на вопросы)|реагиру\w*|"
                      r"может (?:ли )?(?:разговаривать|говорить)|потерял сознание|"
                      r"установить контакт|на голос\b.{0,35}\bреагиру\w*)\b",),
    "danger": (r"\b(?:безопасн\w*|опасн\w*|опасност\w*|угроз\w*|угрожает|угрожают|"
               r"можете (?:ли )?(?:выйти|отойти)|безопасно (?:ли )?оставаться)\b",),
    "fire": (r"\b(?:огонь|огня|пламя|дым\w*|пожар(?!н)\w*|возгора\w*|гор\w*|горени\w*)\b",),
    "weapon": (r"\b(?:оружи\w*|нож\w*|пистолет\w*|вооруж\w*)\b",),
    "description": (r"\b(?:примет\w*|внешност\w*|выглядел\w*|"
                    r"(?:опишите|описать) (?:людей|участников|нападавш\w*|подозреваем\w*))\b",),
    "vehicle": (r"\b(?:машин\w*|автомобил\w*|транспорт\w*|номер (?:машины|автомобиля)|"
                r"регистрационн\w* знак\w*|марку и расцветку)\b",),
    "victims": (r"\b(?:есть ли (?:там |у вас )?(?:пострадавш\w*|ранен\w*|люди)|"
                r"кто (?:нибудь )?пострадал|получил\w* (?:травм\w*|ранени\w*)|"
                r"кому нужна (?:скорая|помощь)|люди (?:внутри|которым нужна помощь)|"
                r"остались ли люди|есть ли у .{0,30} травм\w*|"
                r"(?:из )?присутствующ\w* есть\b.{0,25}\bтравм\w*|"
                r"врач нужен кому|врач нужен)\b",),
    "help_sent": (r"\b(?:помощь (?:уже )?(?:едет|выехала|направлена)|"
                  r"(?:бригада|спасатели|пожарные) (?:уже )?(?:едет|едут|выехали|в пути)|"
                  r"я (?:отправил|направил) (?:помощь|бригаду|пожарных)|"
                  r"службы оповещены|"
                  r"машин\w* с сотрудниками уже выслал\w*|"
                  r"спасательная группа выдвинулась)\b",),
    "not_sent": (r"\b(?:пока никого не отправлял\w*|"
                 r"(?:помощь|бригада) еще не (?:отправлена|выехала|направлена)|"
                 r"я (?:пока )?не (?:отправил|направил)|выезд пока не подтвержден|"
                 r"машин\w* к вам еще не направлял\w*)\b",),
    "hold": (r"\b(?:оставайтесь на линии|не кладите трубку|"
             r"подождите на линии|не отключайтесь|оставайтесь на связи|"
             r"побудьте на телефоне)\b",),
    "reassure": (r"\b(?:не волнуйтесь|сохраняйте спокойствие|я вам помогу|"
                 r"я остаюсь с вами|будем разбираться вместе)\b",),
    "dismissal": (r"\b(?:ищите помощь сами|не занимайте линию)\b",),
    "goodbye": (r"\b(?:до свидания|положите трубку|можете завершить разговор|"
                r"разговор окончен|всего доброго|на этом закончим|"
                r"можете повесить трубку|можете отключаться)\b",),
}

_PATTERNS = {label: tuple(re.compile(pattern) for pattern in patterns)
             for label, patterns in _FIELDS.items()}
_REPEAT = re.compile(r"\b(?:повторите|повтори|скажите еще раз|не расслышал|"
                     r"снова назовите|еще раз пожалуйста|повторно записать)\b")
_CONTACT = re.compile(r"\b(?:алло|слышите меня|меня слышно|вы на линии|"
                      r"я вас слышу|проверка связи|я слушаю|"
                      r"слышите что я говорю|прием вы здесь)\b")
_KNOWN = re.compile(r"\b(?:адрес|телефон|имя|номер|описание происшествия) (?:мы уже выяснили|мне уже известен|"
                    r"успел записать|повторять не требуется)\b")


def strip_known(text: str) -> str:
    normalized = operator_text(text)
    cleaned = _KNOWN.sub("", normalized).strip()
    return text if cleaned == normalized else cleaned


def evidence(text: str) -> tuple[str, ...]:
    words = operator_text(strip_known(text))
    matches = []
    for label, patterns in _PATTERNS.items():
        start = min((match.start() for pattern in patterns
                     if (match := pattern.search(words)) is not None), default=None)
        if start is not None:
            matches.append((start, label))
    labels = [label for _, label in sorted(matches)]
    if "fire" in labels and "address" in labels and re.search(
        r"\b(?:горени\w*|пламя|огонь|дым) где именно (?:наблюда\w*|видн\w*|идет)", words
    ) and not re.search(r"\b(?:адрес\w*|улиц\w*|дом\w*|населенн\w* пункт|местоположени\w*|"
                        r"где конкретно требуется)\b", words):
        labels.remove("address")
    if "danger" in labels and "address" in labels and re.search(
        r"\bместо где вы (?:ждете|находитесь).{0,35}\b(?:угроз\w*|опасн\w*)", words
    ):
        labels.remove("address")
    if "victim_count" in labels or "age" in labels:
        # A count or age question alone does not also ask whether anyone was hurt.
        if not re.search(r"\b(?:есть ли|кто|кому|врач нужен)\b.{0,35}\b(?:пострад|ранен|травм|люди|кому)", words):
            labels = [label for label in labels if label != "victims"]
    if "help_sent" in labels or "not_sent" in labels:
        labels = [label for label in labels if label != "vehicle"]
    if "hold" in labels and "телефоне" in words and "phone" in labels:
        labels.remove("phone")
    return tuple(labels)


def explicit_action(text: str, targets: tuple[str, ...]) -> str | None:
    words = operator_text(text)
    if _REPEAT.search(words) and not any(target in targets for target in
                                          ("help_sent", "not_sent", "hold", "reassure")):
        return "repeat"
    if _CONTACT.search(words) and not targets:
        return "contact"
    if targets:
        if set(targets) == {"goodbye"}:
            return "end"
        if set(targets) <= {"help_sent", "not_sent", "hold", "reassure", "dismissal", "goodbye"}:
            return "inform"
        return "request"
    return None
