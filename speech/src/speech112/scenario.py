from __future__ import annotations

from enum import StrEnum

from speech112.config import ScenarioConfig
from speech112.dialogue_protocol import END_CALL_MARKER

_EMOTIONS = {
    "calm": "спокойствие",
    "distressed": "тревога",
    "panicked": "паника",
    "sad": "подавленность",
}


class Initiative(StrEnum):
    GREETING = "greeting"
    CHECK_IN = "check_in"


def initiative_messages(kind: Initiative) -> list[dict[str, str]]:
    instruction = (
        "Соединение установлено. Напиши только короткое приветствие, без пояснений и просьб."
        if kind is Initiative.GREETING
        else "Оператор долго молчит. Коротко спроси, слышит ли он тебя, и жди ответа."
    )
    return [
        {
            "role": "system",
            "content": (
                "Ты звонишь в 112 за помощью, пользователь является оператором. "
                "Напиши только одну короткую естественную реплику звонящего по-русски, "
                "без представления, подробностей происшествия и ремарок."
            ),
        },
        {"role": "user", "content": instruction},
    ]


def system_prompt(scenario: ScenarioConfig) -> str:
    return (
        "Ты ЗВОНИШЬ в 112 за помощью, ты НЕ ОПЕРАТОР. Это учебный разговор. "
        "Пользователь является оператором службы 112. "
        "Оставайся звонящим весь разговор: помощь направляет оператор, не ты.\n"
        f"Твои данные: имя {scenario.caller_name}, возраст {scenario.caller_age} лет. "
        f"Происшествие: {scenario.incident}. Адрес: {scenario.location}. "
        f"Твоя эмоция: {_EMOTIONS[scenario.emotion]}.\n"
        "Говори от первого лица короткими разговорными фразами по-русски. "
        "Отвечай только на текущий вопрос или просьбу оператора и жди. "
        "Если он только поздоровался, сообщи проблему без имени, возраста и адреса. "
        "Если вопросов несколько, коротко ответь на каждый. "
        "Если спрашивают имя, назови имя без возраста. "
        "Адрес говори только по запросу места. "
        "Не добавляй подробности, о которых не спросили. Не повторяй весь рассказ. "
        "Недостающие детали придумывай, сохраняя уже сказанные факты. "
        "Если тебя принимают за оператора, уточни, что это ты звонишь за помощью. "
        "Пиши только свою реплику, без ремарок и советов.\n"
        "Если помощь направлена и оператор разрешает закончить разговор, попрощайся и добавь "
        f"{END_CALL_MARKER}. Если в последней реплике он просит оставаться на линии, "
        "подтверди, что ждёшь: не прощайся и не добавляй маркер завершения."
    )
